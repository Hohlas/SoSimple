export const meta = {
  name: 'retrospective-v2',
  description: 'Ретроспектива проекта: fan-out по направлениям исследований. Читает CHANGELOG, docs/reports/ и ML/reports/, группирует отчёты по направлениям, параллельно анализирует каждое направление, синтезирует итоговый документ.',
  phases: ['Разведка', 'Чтение по направлениям', 'Синтез', 'Верификация'],
};

// ═══════════════════════════════════════════════════════
// Фаза 1: Разведка
// Один агент читает CHANGELOG.md, выделяет направления
// и привязывает отчёты к каждому направлению.
// ═══════════════════════════════════════════════════════

phase('Разведка');
log('Читаю CHANGELOG.md для построения карты направлений...');

const indexRaw = await agent(
  `Прочитай CHANGELOG.md полностью. Также просмотри каталог ML/reports/ —
там могут быть отчёты, не упомянутые в CHANGELOG.
Выдели направления исследований — группы связанных этапов с общей гипотезой.

Включи ВСЕ этапы с самого начала проекта, а не только избранные месяцы.

Для каждого направления укажи:
- name: краткое название (2-4 слова)
- goal: цель направления
- hypothesis: основная гипотеза
- reports: массив путей к отчётам (docs/reports/YYYY-MM-DD-topic.md
  и/или ML/reports/имя_файла.md)

Правила:
- Каждый отчёт из CHANGELOG и ML/reports/ должен попасть хотя бы в одно направление.
- Если отчёт относится к нескольким направлениям, включи в оба.
- Игнорируй записи про баги инфраструктуры, рефакторинг без изменения поведения, опечатки.
- Если направление содержит только один отчёт — всё равно включи его.

Разбиение направлений:
- Разная гипотеза = разное направление, даже если тема пересекается.
- Самостоятельные линии с собственными вердиктами (PASS/FAIL)
  не сливай с другими направлениями.
- Подэтап без собственной гипотезы (подготовка, инфраструктура,
  побочный диагноз, sub-study внутри более широкой линии) не выделяй
  в отдельное направление — описывай в разделе родителя.
  Критерий: если у группы этапов нет гипотезы, отличной от гипотезы
  соседа/родителя, это подэтап, а не направление.

Ответь ИСКЛЮЧИТЕЛЬНО валидным JSON без markdown-обёртки:
{
  "directions": [
    {
      "name": "...",
      "goal": "...",
      "hypothesis": "...",
      "reports": ["docs/reports/...", "ML/reports/..."]
    }
  ]
}`,
  { phase: 'Разведка', label: 'Карта направлений' }
);

let directions;
try {
  let extracted = indexRaw;
  if (typeof indexRaw === 'object' && indexRaw !== null) {
    if (indexRaw.content) {
      extracted = indexRaw.content;
    } else if (indexRaw.directions) {
      directions = indexRaw.directions;
    }
  }

  if (!directions) {
    let raw = typeof extracted === 'string' ? extracted : JSON.stringify(extracted);
    let cleaned = raw.trim();
    cleaned = cleaned.replace(/^```(?:json)?\s*\n?/i, '').replace(/\n?```\s*$/i, '');
    let parsed;
    try {
      parsed = JSON.parse(cleaned);
    } catch (_) {
      const match = cleaned.match(/\{[\s\S]*"directions"[\s\S]*\}/);
      if (match) {
        parsed = JSON.parse(match[0]);
      } else {
        throw new Error('Could not extract JSON from agent response');
      }
    }
    directions = parsed.directions;
  }
} catch (e) {
  log('ОШИБКА: не удалось распарсить JSON от агента разведки. Завершаю.');
  log('Ответ агента (первые 500 символов): ' + String(indexRaw).slice(0, 500));
  throw new Error('Parse error: ' + e.message);
}

if (!directions || directions.length === 0) {
  log('ОШИБКА: агент разведки не нашёл ни одного направления. Завершаю.');
  throw new Error('No directions found');
}

log(`Найдено направлений: ${directions.length} — ${directions.map(d => d.name).join(', ')}`);

// ═══════════════════════════════════════════════════════
// Фаза 2: Параллельное чтение по направлениям
// Один агент на направление, читает свои отчёты.
// ═══════════════════════════════════════════════════════

phase('Чтение по направлениям');
log(`Запускаю ${directions.length} агентов параллельно...`);

const rawResults = await parallel(
  directions.map(dir => () =>
    agent(
      `Направление исследования: ${dir.name}
Цель: ${dir.goal}
Гипотеза: ${dir.hypothesis}

Прочитай каждый отчёт из списка:
${dir.reports.join('\n')}

Если отчёт не найден — пропусти и продолжи.

Для каждого отчёта извлеки:
- заголовок
- дата
- вердикт (из header, поле "Вердикт" — обычно PASS/FAIL/DIAGNOSTIC_ONLY, но могут встречаться другие значения; указывай как в отчёте)
- цель этапа (из header, поле "Цель")
- что сделано (из секции "What Was Done", кратко)
- метрики с конкретными числами и размером выборки (из секции "Results")
- вывод (из секции "Conclusions")

В конце — итог по направлению:
- сколько этапов PASS, FAIL, DIAGNOSTIC_ONLY
- общий вывод: дало ли направление положительный результат
- ключевой вклад направления в проект

Ответь в формате markdown. Для каждого отчёта — отдельный подзаголовок.`,
      { phase: 'Чтение по направлениям', label: dir.name }
    )
  )
);

const results = rawResults.filter(Boolean);
log(`Получено результатов: ${results.length} из ${directions.length}`);

// ═══════════════════════════════════════════════════════
// Фаза 3: Синтез
// Один агент получает все результаты и пишет документ.
// ═══════════════════════════════════════════════════════

phase('Синтез');
log('Синтезирую итоговый документ...');

const analysisBlock = results
  .map((r, i) => `\n---\n## Направление: ${directions[i]?.name || 'неизвестно'}\n${r}`)
  .join('\n');

await agent(
  `Ты пишешь итоговый документ ретроспективы проекта.

Период документа: с начала проекта по текущий момент.
Не ограничивай последними месяцами.

Порог успеха: PF ≥ 1.3 на out-of-sample с учётом спреда и проскальзываний,
подтверждённый bootstrap CI (нижняя граница > 1.0).

Ниже — анализ по направлениям исследований:

${analysisBlock}

Дополнительно прочитай wiki/research/ и каталог ML/reports/ для контекста.

Напиши документ docs/reports/retrospective.md (не более 4000 слов) со структурой:

1. Вердикт по проекту (1 абзац)
   Достигнут ли порог успеха. Если нет — какая главная причина.

2. Направления исследований
   Сохраняй границы направлений из входных данных: один подраздел
   на одно направление. Не сливай соседние и не дроби дальше.
   Для каждого: цель, гипотеза, ключевые этапы с вердиктами
   (PASS/FAIL/DIAGNOSTIC_ONLY) и метриками, итог направления.

3. Что работает
   Решения с измеримым положительным эффектом. Для каждого:
   метрика до, метрика после, размер выборки, вердикт.

4. Что не работает
   Подходы с отрицательным или нулевым результатом. Для каждого:
   что пробовали, конкретные числа, почему не сработало (гипотеза).

5. Эволюция понимания
   Как менялось представление о проблеме за год. Какие убеждения
   оказались неверными и когда это стало ясно.

6. Нерешённые проблемы
   Открытые вопросы, блокирующие прогресс. Для каждого:
   что известно, что нужно выяснить, предлагаемый подход.

7. Накопленные ограничения
   Ограничения данных, моделей, пайплайна, методологии,
   которые сужают пространство поиска.

8. Рекомендации
   Что пробовать дальше (с обоснованием). Что закрыть окончательно
   (с обоснованием). Приоритеты на следующий квартал.

Правила:
- Для каждой метрики — конкретные числа и размер выборки.
- Критерий включения: факт влияет на выбор дальнейшей стратегии.
- Исключай: баги инфраструктуры, опечатки, рефакторинг без изменения поведения.
- При противоречии между данными из разных направлений — укажи противоречие явно.
- Используй инструмент Write для записи результата в docs/reports/retrospective.md.`,
  { phase: 'Синтез', label: 'Итоговый документ' }
);

log('Ретроспектива записана в docs/reports/retrospective.md');

// ═══════════════════════════════════════════════════════
// Фаза 4: Верификация
// Агент проверяет факты по первоисточникам.
// ═══════════════════════════════════════════════════════

phase('Верификация');
log('Проверяю факты по первоисточникам...');

const correctionsRaw = await agent(
  `Прочитай docs/reports/retrospective.md. Выбери 10 утверждений
с конкретными числами (PF, win rate, Spearman, N сделок, BS_p05).

Для каждого:
1. Найди первоисточник в docs/reports/ (файл отчёта).
2. Сверь число с первоисточником.
3. Если число неверное — укажи правильное со ссылкой на файл и строку.

Ответь в формате markdown:
## Верификация

### Подтверждено (число совпадает)
- Утверждение — источник: файл, число

### Исправления
- Секция X: было "PF=8.18" — правильно "PF=8.12" (источник: docs/reports/..., строка Y)

Если все 10 утверждений верны — напиши "Все проверенные факты подтверждены."`,
  { phase: 'Верификация', label: 'Проверка фактов' }
);

log('Верификация завершена.');

await agent(
  `Прочитай docs/reports/retrospective.md.
Ниже — результаты верификации фактов:

${correctionsRaw}

Если есть исправления — внеси их в docs/reports/retrospective.md через Edit.
Если все факты подтверждены — не изменяй файл.
В конце напиши краткий отчёт: сколько фактов проверено, сколько исправлено.`,
  { phase: 'Верификация', label: 'Применение исправлений' }
);

log('Верификация и исправления завершены.');
