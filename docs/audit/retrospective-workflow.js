let directions;
try {
  let extracted = indexRaw;
  if (typeof indexRaw === 'object' && indexRaw !== null) {
    if (indexRaw.content) {
      extracted = indexRaw.content;
    } else if (indexRaw.directions) {
      directions = indexRaw.directions;
    }
  }

  if (!directions) {
    let raw = typeof extracted === 'string' ? extracted : JSON.stringify(extracted);
    let cleaned = raw.trim();
    cleaned = cleaned.replace(/^```(?:json)?\s*\n?/i, '').replace(/\n?```\s*$/i, '');
    let parsed;
    try {
      parsed = JSON.parse(cleaned);
    } catch (_) {
      // Берём самый внешний JSON-объект: от первой '{' до последней '}'.
      const first = cleaned.indexOf('{');
      const last = cleaned.lastIndexOf('}');
      if (first !== -1 && last !== -1 && last > first) {
        parsed = JSON.parse(cleaned.slice(first, last + 1));
      } else {
        throw new Error('Could not extract JSON from agent response');
      }
    }
    directions = parsed.directions;
  }
} catch (e) {
  log('ОШИБКА: не удалось распарсить JSON от агента разведки. Завершаю.');
  log('Ответ агента (первые 500 символов): ' + String(indexRaw).slice(0, 500));
  throw new Error('Parse error: ' + e.message);
}

if (!directions || directions.length === 0) {
  log('ОШИБКА: агент разведки не нашёл ни одного направления. Завершаю.');
  throw new Error('No directions found');
}

// Нормализация: reports приводим к массиву строк (агент мог вернуть объекты
// или строки — поддерживаем оба), singleton высчитываем по длине reports
// (=1 → singleton). Не полагаемся на добросовестность агента в проставлении
// поля singleton в JSON — это детерминированная проверка.
directions = directions.map(d => {
  const rawReports = Array.isArray(d.reports) ? d.reports : [];
  const reports = rawReports
    .map(r => (typeof r === 'string' ? r : (r && r.path) || ''))
    .filter(Boolean);
  return {
    name: d.name,
    goal: d.goal,
    hypothesis: d.hypothesis,
    reports,
    singleton: reports.length === 1,
  };
});

log(`Найдено направлений: ${directions.length} — ${directions.map(d => d.name).join(', ')}`);
log(`Singleton: ${directions.filter(d => d.singleton).length}`);

